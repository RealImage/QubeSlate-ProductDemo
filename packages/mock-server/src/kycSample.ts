import type { Company, KycDoc, KycFile } from '@slate/domain';

export const kycFileKey = (companyId: string, kind: KycDoc['kind']) => `${companyId}|${kind}`;

/** A one-page placeholder PDF, so seeded KYC documents (which have no uploaded content) can still be previewed. */
export function sampleKycFile(c: Pick<Company, 'name' | 'gstin' | 'pan'>, doc: KycDoc): KycFile {
  const lines = [doc.kind, c.name, `GSTIN ${c.gstin}   PAN ${c.pan}`, '', 'Sample document generated by the Qube Slate prototype.', `File: ${doc.fileName ?? ''}`];
  const esc = (s: string) => s.replace(/[\\()]/g, m => `\\${m}`).replace(/[^\x20-\x7e]/g, '?');
  const text = lines.map((l, i) => `BT /F1 ${i === 0 ? 20 : 12} Tf 72 ${740 - i * 28} Td (${esc(l)}) Tj ET`).join('\n');
  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>',
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
    `<< /Length ${text.length} >>\nstream\n${text}\nendstream`
  ];
  let pdf = '%PDF-1.4\n';
  const offsets = objects.map((o, i) => { const at = pdf.length; pdf += `${i + 1} 0 obj\n${o}\nendobj\n`; return at; });
  const xref = pdf.length;
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n${offsets.map(o => `${String(o).padStart(10, '0')} 00000 n \n`).join('')}`;
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
  return { fileName: doc.fileName ?? `${doc.kind}.pdf`, mimeType: 'application/pdf', dataUrl: `data:application/pdf;base64,${Buffer.from(pdf, 'latin1').toString('base64')}` };
}
